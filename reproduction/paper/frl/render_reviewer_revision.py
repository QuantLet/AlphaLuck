"""Render descriptive FRL tables from the paired and exposure-based audits.

Run after paired_denominator_sensitivity.py and frozen_book_robustness.py.
The legacy core/audit macro files are not modified.
"""
from pathlib import Path
import json
import pandas as pd

ROOT=Path(__file__).resolve().parents[2]
HERE=ROOT/'paper/frl'
DER=ROOT/'data/derived'


DENOMINATOR_NOTE=r'''\par\smallskip\parbox{0.92\linewidth}{\footnotesize\textit{Note.} Equity
uses lagged daily equity for volatility, contemporaneous equity for gross
exposure and mean date-end equity for turnover; initial uses starting capital
throughout. $F$ is the additive model/residual mean-square ratio, $W$ is rank
concordance across arms, and $\rho$ is mean within-arm rank correlation with
final return. Permutation $p$-values in parentheses (two-sided for $\rho$,
one-sided for $F$ and $W$; 20{,}000 within-arm draws) condition on the
observed panel and market path; Holm adjustment and an exact profile test are
in the Online Appendix.}'''

def render(destination=HERE):
    destination=Path(destination)
    destination.mkdir(parents=True,exist_ok=True)
    inference=HERE/'review_results/inference'
    paired=json.loads((inference/'paired_denominator_report.json').read_text())
    comparison=pd.read_csv(inference/'denominator_comparison.csv')
    benchmark=json.loads((DER/'frozen_book_robustness.json').read_text())
    scenarios=pd.read_csv(DER/'frozen_book_robustness_scenarios.csv')
    main=next(x for x in benchmark['summaries'] if x['freeze_hours']==24)
    stress=scenarios[(scenarios.freeze_hours==24)&(scenarios.scenario=='terminal_friction')
                     &(scenarios.convention=='frozen_only')&(scenarios.stress_bps==100)].iloc[0]
    vals={
      'alReviewEndpointBreak':f"{main['endpoint_common_market_break_even_pct']:.2f}",
      'alReviewAccountBound':f"{main['endpoint_accountwise_bound_break_even_pct']:.2f}",
      'alReviewCostBreak':f"{main['frozen_only_break_even_friction_bps']:.2f}",
      'alReviewCloseStress':'100',
      'alReviewCloseGap':f"{stress.advantage_pp:.2f}",
      'alReviewFundingBound':f"{main['funding_oracle_10pct_common_error_gap_lower_bound_pp']:.2f}",
      'alReviewMinMargin':f"{100*main['minimum_aggregate_equity_to_gross']:.2f}",
      'alReviewFeeBps':f"{benchmark['empirical_fee_context']['notional_weighted_fee_bps']:.2f}",
      'alReviewFrozenGross':f"{main['frozen_terminal_gross']:,.0f}".replace(',','{,}'),
      'alReviewActualGross':f"{main['actual_terminal_gross']:,.0f}".replace(',','{,}'),
    }
    for unit in ['date','model','arm']:
        d=paired['leave_one_out_ranges'][unit]['delta_rho']
        for suffix,key in [('Lo','min'),('Hi','max')]:
            vals['alReview'+unit.title()+'Delta'+suffix]=f"{d[key]:.3f}"
    (destination/'review_numbers.tex').write_text('% Generated by render_reviewer_revision.py\n'+
        '\n'.join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in vals.items())+'\n')
    (destination/'review_numbers.json').write_text(json.dumps(vals,indent=2)+'\n')

    text=r'''\begin{table}[ht]
\centering\small
\caption{Risk measures on current equity and initial capital, Season~1.5.}
\label{tab:trait}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrrrr}
\toprule
 & \multicolumn{2}{c}{$F$} & \multicolumn{2}{c}{$W$} & \multicolumn{2}{c}{$\rho$} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}
Measure & Equity & Initial & Equity & Initial & Equity & Initial \\
\midrule
'''
    names={'vol':'Volatility','leverage':'Gross exposure','turnover':'Turnover'}
    perm=json.loads((DER/'i6_vol_denominator.json').read_text())
    key={'vol':'vol','leverage':'leverage','turnover':'turnover'}
    fmt=lambda x:'($<0.001$)' if x<0.001 else f'(${x:.3f}$)'
    for r in comparison.to_dict('records'):
        values=[r[d+'_'+k] for k in ['F','W','rho'] for d in ['equity','fixed']]
        text += names[r['metric']]+' & '+' & '.join(f'${x:.2f}$' for x in values)+r' \\'+'\n'
        ps=[perm[key[r['metric']]+'_'+d][k] for k in ['p_perm','p_W_perm','assoc_p_two_sided']
            for d in ['equity','fixed']]
        text += ' & '+' & '.join(fmt(x) for x in ps)+r' \\'+'\n'
    text+='\\bottomrule\n\\end{tabular}\n'+DENOMINATOR_NOTE+'\n\\end{table}\n'
    (destination/'review_denominators.tex').write_text(text)

    data=pd.read_csv(DER/'a1_pnl_decomposition.csv')
    text=r'''\begin{table}[ht]
\centering\small
\caption{Signed accounting contributions, per cent of initial capital.
The combined timing and execution contribution is $B-X$; separate components
depend on intermediate marks. Funding uses the recorded daily-booked
convention here, unlike the hourly frozen-book comparison. Rounding can
affect the sum of printed entries.}
\label{tab:pnl}
\begin{tabular}{lrrrrr}
\toprule
 & Exposure & Timing + execution & Fees & Funding & Net \\
\midrule
'''
    for sea,name in [('S1','Season 1'),('S15','Season 1.5')]:
        d=data[data.season.eq(sea)]
        g=d.select_dtypes('number').sum()/(10000*len(d))*100
        v=[g.exposure_pnl,g.timing_pnl-g.slippage,-g.fees,g.funding,g.net_pnl]
        assert abs(sum(v[:4])-v[4])<1e-8
        text+=name+' & '+' & '.join(f'${x:.2f}$' for x in v)+r' \\'+'\n'
    text+='\\bottomrule\n\\end{tabular}\n\\end{table}\n'
    (destination/'review_pnl.tex').write_text(text)

    text=r'''\begin{table}[ht]
\centering\small
\caption{Sensitivity of the 24-hour hourly-funded comparison, Season~1.5.
Closing friction is charged only to frozen terminal gross notional. Endpoint
stress applies common per-asset directions adverse to aggregate differential
exposures to both books, holding cash flows fixed. Stress sizes are
hypothetical, not estimated error bounds; advantages are percentage points
of initial capital. No scenario reconstructs liquidation feasibility.}
\label{tab:reviewstress}
\begin{tabular}{lrr}
\toprule
Scenario & Advantage (pp) & Accounts ahead \\
\midrule
'''
    rows=[('Recorded marks, no closing friction',main['advantage_pp'],main['accounts_ahead']),
          ('100 bp closing friction, frozen only',stress.advantage_pp,int(stress.accounts_ahead))]
    for pct in [1,2,5]:
        r=scenarios[(scenarios.freeze_hours==24)&(scenarios.scenario=='endpoint_price_error')
                    &(scenarios.convention=='common_market_adverse')&(scenarios.stress_pct==pct)].iloc[0]
        rows.append((f'{pct}\\% adverse endpoint-price bound',r.advantage_pp,int(r.accounts_ahead)))
    for lab,gap,n in rows:
        text+=f'{lab} & ${gap:.2f}$ & {n}/32'+r' \\'+'\n'
    text+='\\bottomrule\n\\end{tabular}\n\\end{table}\n'
    (destination/'review_benchmark.tex').write_text(text)

    d=pd.read_csv(inference/'joint_block_summary.csv')
    text=r'''\begin{table}[ht]
\centering\small
\caption{Central 95\% ranges from reweighting common date blocks, 20,000 draws
per length. Final season returns remain fixed. These are sensitivity ranges,
not confidence intervals; no probability coverage is claimed. ``Initial''
uses initial-capital volatility and $\Delta\rho=\rho_{\rm initial}-\rho_{\rm equity}$.}
\label{tab:dayweights}
\begin{tabular}{lccc}
\toprule
 & 1-day blocks & 2-day blocks & 3-day blocks \\
\midrule
'''
    for key,lab in [('fixed_F','Initial $F$'),('fixed_W','Initial $W$'),('fixed_rho',r'Initial $\rho$'),
                    ('equity_rho',r'Equity $\rho$'),('delta_rho',r'Paired $\Delta\rho$')]:
        row=[]
        for block in [1,2,3]:
            r=d[(d.statistic==key)&(d.block_days==block)].iloc[0]
            row.append(f"$[{r['q025']:.3f},\\,{r['q975']:.3f}]$")
        text+=lab+' & '+' & '.join(row)+r' \\'+'\n'
    text+='\\bottomrule\n\\end{tabular}\n\\end{table}\n'
    (destination/'review_day_sensitivity.tex').write_text(text)
    print('Generated reviewer numbers and four descriptive tables.')

if __name__=='__main__':
    render()
