"""Generate the oracle-validation macros from data/derived/oracle_validation.json."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
d = json.loads((ROOT / 'data/derived/oracle_validation.json').read_text())
liq = __import__('pandas').read_csv(
    ROOT / 'data/derived/organiser_hourly/oracle_liquidation_check.csv')

org = d['organiser_current_price_vs_oracle']['all']
ins = d['in_season_daily_aggregates']['organiser_vs_oracle']
imp = d['implied_oracle']
fund = d['funding_refetch_vs_stored']
user = d['user_vs_public_funding_rate']
seen = liq.dropna(subset=['mark_vs_oracle_prev_bps', 'mark_vs_oracle_next_bps'])
gaps = sorted(abs(x) for x in seen[['mark_vs_oracle_prev_bps',
                                     'mark_vs_oracle_next_bps']].values.ravel())

values = {
    'OracleCoinHours': f"{imp['coin_hours']:,}",
    'OracleDispMax': f"{imp['dispersion_bps_max']:.1f}",
    'OracleN': f"{org['n']:,}",
    'OracleMedAbs': f"{org['median_abs_bps']:.1f}",
    'OracleNinetyNine': f"{org['p99_abs_bps']:.0f}",
    'OracleMaxPct': f"{org['max_abs_bps'] / 100:.1f}",
    'OracleTenShare': f"{100 * org['share_within_10bps']:.0f}",
    'OraclePoolMedAbs': f"{d['pooled_print_vs_oracle']['median_abs_bps']:.1f}",
    'OraclePoolSeasonMedAbs': f"{d['in_season_daily_aggregates']['pooled_vs_oracle']['median_abs_bps']:.1f}",
    'OracleSeasonN': f"{ins['n']:,}",
    'OracleSeasonMedAbs': f"{ins['median_abs_bps']:.1f}",
    'OracleSeasonMaxPct': f"{ins['max_abs_bps'] / 100:.1f}",
    'OracleFundRows': f"{fund['rate_exact_equal']:,}",
    'OracleUserRows': f"{user['matched_to_public_hour']:,}",
    'OracleLiqEvents': f"{len(seen)}",
    'OracleLiqGapLo': f"{gaps[0] / 100:.1f}",
    'OracleLiqGapHi': f"{gaps[-1] / 100:.1f}",
}
assert user['rate_rel_diff_max'] == 0 and fund['rate_exact_equal'] == fund['stored_rows']
(ROOT / 'paper/frl/oracle_numbers.tex').write_text(
    '% Generated by render_oracle_numbers.py\n' + ''.join(
        f'\\newcommand{{\\al{k}}}{{{v}}}\n' for k, v in values.items()))
print('Generated oracle macros.')
