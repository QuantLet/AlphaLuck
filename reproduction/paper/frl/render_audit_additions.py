"""Generate FRL audit tables and numbers from regenerated results."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / 'paper/frl'
DER = ROOT / 'data/derived'

def read(path):
    return json.loads(path.read_text())

def minus(s):
    # A typed hyphen is not a minus sign; \ensuremath{-} works in text and
    # maths alike, as in make_numbers.py.
    return re.sub(r'(?<![\w.\\{])-(?=\d)', r'\\ensuremath{-}', s)

def main():
    cost = read(HERE / 'benchmark_cost_sensitivity.json')
    funding = read(DER / 'hourly_funding_benchmark_sensitivity.json')
    validation = read(DER / 'hourly_rate_aggregation_validation.json')
    v = read(DER / 'i6_vol_denominator.json')
    r = next(x for x in funding['results'] if x['freeze_h'] == 24)
    c = next(x for x in cost['scenarios'] if x['debit_pp'] == 0)
    ten = next(x for x in cost['scenarios'] if x['debit_pp'] == 10)
    values = {
        'alFundingHoldPct': f"{r['hold']/3200:.2f}",
        'alFundingRealPct': f"{r['actual']/3200:.2f}",
        'alFundingAhead': str(r['better']),
        'alFundingVolF': f"{funding['volatility_F']:.2f}",
        'alCostGapPct': f"{c['advantage_pp']:.2f}",
        'alCostTenAhead': str(ten['accounts_ahead']),
        'alCostGapUSD': f"{cost['advantage_dollars']:,.2f}".replace(',', '{,}'),
        'alCostHoldUSD': f"{cost['frozen_profit']:,.2f}".replace(',', '{,}'),
    }
    audit = read(HERE / 'referee_audit.json')
    for prefix, key in [('alAuditAgg', 'hac1_aggregate'), ('alAuditEqual', 'hac1_equal_daily')]:
        for suffix, field in [('Median','median'),('QOne','q1'),('QThree','q3')]:
            values[prefix+suffix] = f"{audit[key][field]:.2f}"
    for prefix, key in [('alAuditArm','leave_one_arm'),('alAuditDay','leave_one_return_day')]:
        for field, precision in [('F',2),('W',3)]:
            vals = [r[field] for r in audit[key]]
            values[prefix+field+'Min'] = f"{min(vals):.{precision}f}"
            values[prefix+field+'Max'] = f"{max(vals):.{precision}f}"
    last = max(audit['leave_one_return_day'], key=lambda r: r['omitted_day'])
    values['alAuditLastF'] = f"{last['F']:.2f}"
    values['alAuditLastW'] = f"{last['W']:.3f}"
    (HERE / 'audit_addition_numbers.tex').write_text(
        '% Generated by render_audit_additions.py\n' + '\n'.join(
            '\\newcommand{\\'+k+'}{'+minus(val)+'}' for k, val in values.items())+'\n')
    text = r'''% Generated by render_audit_additions.py
\begin{table}[ht]
\centering
\caption{Terminal sensitivity to omitted net costs, Season~1.5, 24-hour
freeze, under the recorded daily-funding convention. Returns and advantages
are per cent of initial capital. Counts use unrounded account-level values.}
\label{tab:omittedcost}
\begin{tabular}{rrrr}
\toprule
Debit $c$ & Frozen return & Advantage & Accounts ahead \\
\midrule
'''
    for row in cost['scenarios']:
        text += minus(f"{row['debit_pp']} & {row['frozen_return_pct']:.2f} & {row['advantage_pp']:.2f} & {row['accounts_ahead']}/32") + r' \\'+'\n'
    text += '\\bottomrule\n\\end{tabular}\n\\end{table}\n'
    (HERE/'audit_cost_table.tex').write_text(text)
    text = r'''\paragraph{Hourly-funding accounting specification.}
We fetch the exchange's historical hourly rates and reconstruct payments as
$-q_{ik,h}P_{k,h}r_{k,h}$, using actual positions just before each nominal
UTC settlement hour and the last pooled trade price at that hour in place of
historical oracle prices not obtained for this analysis. API timestamps are floored to the
hour. Zero positions contribute zero; every nonzero position must have a
finite rate and price. The official window includes 338 hourly observations
for each of seven instruments. Daily aggregates of the reconstructed actual
payments have correlation CORR with recorded cash flows and mean absolute
error of \$MAE across 2,558 rows. This agreement supports the aggregation
interpretation, not the oracle prices on every hypothetical position.

For each path we remove daily-booked funding and add reconstructed hourly
payments only through formation or the official close, as appropriate.
After formation the frozen path uses fixed signed quantities. Its hourly
payments enter the equity path before the margin-proxy check. Table~\ref{tab:hourfund}
reports the result; closing costs and market impact remain excluded.
The descriptive volatility mean-square ratio becomes $F=\alFundingVolF$ and its rank
concordance is unchanged. Pooled prices may be hours old, especially when
equity markets are closed. Historical oracle prices and actual liquidation
rules remain unverified. This is the primary conditional accounting
comparison, not a liquidation replay.

\begin{table}[ht]
\centering\small
\caption{Hourly funding with pooled-price proxy, Season~1.5. Returns and
advantages are per cent of initial capital; screen flags use assumed
aggregate thresholds of 2.5 and 5 per cent of gross notional. They are not
simulated liquidations.}
\label{tab:hourfund}
\begin{tabular}{rrrrrr}
\toprule
Freeze (h) & Frozen & Realised & Advantage & Ahead & Flags \\
\midrule
'''.replace('CORR', f"{validation['correlation']:.6f}").replace('MAE',f"{validation['dollar_mae']:.4f}")
    for row in funding['results']:
        text += minus(f"{row['freeze_h']} & {row['hold']/3200:.2f} & {row['actual']/3200:.2f} & {row['advantage']/3200:.2f} & {row['better']}/32 & {row['breaches_025']}/{row['breaches_05']}") + r' \\'+'\n'
    text += '\\bottomrule\n\\end{tabular}\n\\end{table}\n'
    (HERE/'audit_funding.tex').write_text(text)
    old = (HERE/'audit_voldenom.tex').read_text()
    start = old.index('Model effect,')
    end = old.index(r'\bottomrule', start)
    metrics = ['vol_equity','vol_fixed','turnover_equity','turnover_fixed','leverage_equity','leverage_fixed']
    labels = [('Model effect, $F_{7,21}$','F_model'),(r'\quad permutation $p$','p_perm'),
              ('Arm-adjusted ICC','icc'),("Kendall's $W$ across arms",'W'),
              ('Arm effect, $F_{3,21}$','F_arm'),(r'Continuation ranks, $\rho$','persist_rho'),
              (r'Association with return, $\rho$','assoc_rho'),(r'\quad permutation $p$','assoc_p_two_sided')]
    lines=[]
    for label,key in labels:
        vals=[]
        for metric in metrics:
            x=v[metric][key]
            vals.append('$<0.001$' if key in ('p_perm','assoc_p_two_sided') and x<.001 else f'{x:.3f}' if key in ('p_perm','assoc_p_two_sided') else f'{x:.2f}')
        lines.append(label+' & '+minus(' & '.join(vals))+r' \\')
    (HERE/'audit_voldenom.tex').write_text(old[:start]+'\n'.join(lines)+'\n'+old[end:])
    print('Generated audit numbers and three appendix tables.')

if __name__ == '__main__':
    main()
